/**
 * 유지비율 대조 게이트 — 화면 규약 (D)
 * ---------------------------------------------------------------------------
 * 엔진의 `ratioAgreement`가 판정하고, 이 파일은 그 판정을 **화면이 어떻게 말하는지**만
 * 정한다. 판정 로직은 여기 없다 — freshness-view.ts와 같은 구조다.
 *
 * ── 무엇을 고치는가 ───────────────────────────────────────────────────
 * 조건카드의 유지비율(`ratio_rules[].ratio`)과 계좌 원장의 유지비율
 * (`ACCOUNT.requiredRatio`)은 **서로 다른 곳에서 온다.** 카드의 값은 문서에서
 * 오고 원장의 값은 리터럴인데, 둘을 잇는 코드가 없었다. 어긋나면 화면은
 *
 *     "담보비율 135%" + 근거 좌표가 붙은 "유지비율 170%" 배지 + "담보부족 300,000원"
 *
 * 을 **서로 모순 없어 보이는 모습으로** 함께 냈다. 부족액은 140% 기준으로 산출된
 * 값이고, 담보비율은 V/L이라 어느 r에서도 135%로 같아 눈으로도 잡히지 않는다.
 * 게다가 인제스트가 170% 조항을 정확히 뽑을수록 근거 패널의 기존 경고 경로
 * (figureInQuote·otherFigures)는 **더 조용해진다** — 둘 다 "인용문 vs 카드값"만
 * 보고 원장을 보지 않기 때문이다.
 *
 * ── 화면이 말할 수 있는 것의 상한 ─────────────────────────────────────
 * **"둘이 같지 않다"까지다.** 카드가 틀렸다고도 원장이 틀렸다고도 말하지 않는다 —
 * 어느 쪽이 이 계좌에 맞는지 우리는 모른다. 카드 r은 문서 근거를 통과한 값이고
 * 원장 r은 리터럴이다. 여기 있는 모든 문장은 **화면에 나란히 놓인 두 숫자에 대한
 * 사실 진술**이라 사용자가 눈으로 검증할 수 있다 — evidence-view.ts 머리글의
 * "부정만 말한다" 비대칭 규약과 같은 결이다.
 *
 * ⚠ **통과를 "확인됨/검증됨"으로 내지 않는다.** 이 대조가 보는 것은 "두 값이 같은가"
 *   이지 "그 값이 맞는가"가 아니다. 둘이 같이 틀린 경우는 잡지 못한다(메리츠 C∙D군
 *   150% 과소평가가 그 사례 — snapshot.ts 주석). 통과에 배지를 만들면 거짓 안심이고,
 *   evidence-panel.test.tsx의 '긍정 배지 금지' 회귀 검사에도 걸린다.
 *
 * ⚠ **시계에 묶지 않는다.** 신선도(fresh)는 asOf가 필요해 SSR에서 null이지만, r 비교는
 *   시계와 무관하다. useSyncExternalStore 경로에 얹으면 첫 페인트에서 표식이 사라진다.
 *
 * ⚠ **관통 여부(breached)에 묶지 않는다.** 원장 r이 낡아 관통이 안 잡히는 구간이야말로
 *   어긋남이 가장 위험한 자리다(원장 1.2 · 카드 1.4 · 7,300원 → 원장 기준 D=0인데
 *   카드 기준이면 D=1,100,000). 배너는 관통과 무관하게 뜬다.
 */
import { ratioAgreement, type RatioAgreement } from "@marginguard/engine";
import type { ConditionCard, Position, RatioRule } from "@marginguard/engine";

export interface RatioView {
  agreement: RatioAgreement;
  /** 카드 r과 원장 r을 하나로 맞췄는가. false면 처분 수량을 내지 않는다 */
  confirmed: boolean;
  /**
   * 근거 패널이 **좌표·해시와 함께 크게 찍을 조항.** 대조가 좁혀서 본 그 조항이다.
   * 이걸 넘기지 않으면 패널은 `ratio_rules[0]`을 찍고, 룰이 여럿인 카드에서 게이트와
   * 화면이 서로 다른 조항을 보게 된다(evidence-view.ts의 evidenceView 머리글에 실측).
   * 고른 조항이 없으면(NO_RULE·NON_FINITE) null — 그때는 패널이 지어내지 않는다.
   */
  applicableRule: RatioRule | null;
  /**
   * 카드 섹션 배너. **관통 여부·신선도와 무관하게** 뜬다.
   * confirmed면 null — 통과는 아무 말도 하지 않는다(긍정 배지를 만들지 않는다).
   */
  banner: string | null;
  /** 계기판·선택지 비교·다종목이 공유하는 차단 사유 한 줄 (quantBlockReason 계열) */
  blockReason: string | null;
  /** 근거 패널에 붙는 문장 — 카드의 r이 근거 좌표와 함께 크게 찍히는 바로 그 자리 */
  evidenceNote: string | null;
  /** "이대로면 — 산정 불가" 박스의 설명. 부족액 금액은 호출부가 앞에 붙인다 */
  detail: string | null;
}

/** centi(140) → "140%". 격자가 centi라 소수 셋째 자리는 여기서 사라진다(엔진 주석 ⑥) */
const pct = (centi: number): string => `${centi}%`;
/** [140, 150] → "140%, 150%" */
const pctList = (centi: number[]): string => centi.map(pct).join(", ");

/**
 * 배너 꼬리 — **화면에 떠 있는 수치가 어느 r에서 나왔는지** 밝힌다.
 *
 * 없으면 안 되는 이유: 관통 전 화면(기본 가격)에는 담보부족액이 아예 렌더되지 않고
 * 임계가·여유·λ*만 있는데, 셋 다 원장 r로 만든 값이다. 그 구간에서 기준을 말하는
 * 문장이 근거 패널의 "이 화면의 담보부족액은…" 하나뿐이면, 화면에 없는 값을 가리키는
 * 문장만 남고 **실제로 떠 있는 숫자는 어느 문장도 설명하지 않는다.** 그리고 원장 r이
 * 낡아 관통이 안 잡히는 구간이야말로 어긋남이 가장 위험한 자리다.
 *
 * 배너에 붙이는 이유: 어긋남이 있을 때 **항상** 렌더되는 유일한 요소다(관통·신선도·
 * SSR 무관). 담보비율은 V/L이라 r과 무관하므로 여기 넣지 않는다 — 넣으면 틀린 말이다.
 */
/**
 * 화면의 숫자가 **어느 값에서 나왔는지** 말한다.
 *
 * ⚠ 2026-08-24 (#67 A-1, (다) 채택)로 주어가 바뀌었다. 전에는 *"계좌 원장 기준으로
 *   산출했습니다"* 였고 그게 사실이었다 — 임계가·부족액·λ* 가 전부 원장 리터럴에서
 *   나왔다. 이제는 **카드가 구동**한다. 문장을 안 고치면 화면이 거짓을 말한다.
 */
const basisNote = (cards: string): string =>
  ` 이 화면의 임계가·담보부족액·λ*는 조건카드의 ${cards}로 산출했습니다.`;

/**
 * 카드가 유지비율을 못 정하면 **숫자 자체가 없다.** "무엇으로 산출했다"를 말할 수
 * 없으므로 산출하지 않았다고 적는다 — 원장 값을 대신 쓰지 않는다.
 */
const noBasisNote = " 이 카드로는 임계가·담보부족액·λ*를 산출하지 않았습니다.";

/**
 * 카드 r ↔ 원장 r 대조를 화면 문장으로.
 *
 * @param requiredRatio 계좌 원장의 담보유지비율(배수, 예: 1.4)
 * @param pos 종목군 좁히기용 포지션. 없으면 종목군 축을 쓰지 않는다
 */
export function ratioView(
  card: ConditionCard,
  requiredRatio: number,
  pos?: Position,
): RatioView {
  const agreement = ratioAgreement(card, requiredRatio, pos);
  const led = pct(agreement.ledgerRatio);
  /**
   * 근거 패널이 찍을 조항 — **대조가 본 그 조항이다.** 좁히기가 여럿을 남겼어도
   * 그중 첫 조항을 넘긴다: 남은 값들은 문구가 전부 나열하므로, 화면에 찍힌 큰 숫자가
   * 문구가 말하는 값들 **안에** 있게 된다. `ratio_rules[0]`을 그대로 두면 좁히기가
   * 배제한 조항이 근거로 나가 문구와 화면이 다른 숫자를 가리킨다.
   */
  const applicableRule = agreement.selected[0] ?? null;

  if (agreement.agreed) {
    return {
      agreement,
      confirmed: true,
      applicableRule,
      banner: null,
      blockReason: null,
      evidenceNote: null,
      detail: null,
    };
  }

  if (agreement.why === "NON_FINITE") {
    /**
     * 숫자로 읽지 못한 값은 화면에 찍지 않는다 — "NaN%"가 나가는 경로를 막는다.
     * 읽지 못한 쪽이 카드인지 원장인지는 갈린다. 원장이 유한하면 **그 값은 말한다** —
     * 화면에 남아 있는 부족액이 어느 기준으로 나온 것인지는 이 분기에서도 사실이고,
     * 넷 중 이 분기만 침묵하면 그 금액이 기준 없이 서 있게 된다.
     */
    const ledReadable = Number.isFinite(agreement.ledgerRatio);
    return {
      agreement,
      confirmed: false,
      applicableRule,
      banner: ledReadable
        ? `⚠ 조건카드의 유지비율을 숫자로 읽지 못했습니다 — 계좌 원장의 ${led}와 맞춰 보지 못해 처분 수량을 산정하지 않습니다.${noBasisNote}`
        : "⚠ 유지비율을 숫자로 읽지 못했습니다 — 처분 수량을 산정하지 않습니다",
      blockReason: "유지비율을 숫자로 읽지 못했습니다 — 처분 수량을 추정하지 않습니다",
      evidenceNote: ledReadable
        ? `조건카드의 유지비율을 숫자로 읽지 못해 이 화면은 임계가·담보부족액을 산출하지 않았습니다. 계좌 원장의 ${led}로 대신 메우지 않습니다 — 화면이 값을 지어내지 않습니다.`
        : "유지비율을 숫자로 읽지 못해 계좌 원장의 값과 맞춰 보지 못했습니다 — 화면이 그 값을 지어내지 않습니다.",
      // 호출부가 "담보부족액 300,000원은 " 뒤에 그대로 이어 붙인다 — 주어와 붙는
      // 서술어로 시작해야 한다. 넷 중 이 분기만 다른 문장으로 시작하면 금액 자체를
      // 읽지 못한 것처럼 읽힌다.
      detail: ledReadable
        ? `조건카드의 유지비율을 숫자로 읽지 못해 산출하지 않았습니다 — 계좌 원장의 ${led}로 대신 메우지 않습니다. 카드의 조항을 확인한 뒤 다시 보세요.`
        : "유지비율을 숫자로 읽지 못해 산출 기준을 밝힐 수 없는 값입니다 — 처분 수량도 산정하지 않습니다. 카드와 계좌의 유지비율을 확인한 뒤 다시 보세요.",
    };
  }

  if (agreement.why === "NO_RULE") {
    return {
      agreement,
      confirmed: false,
      applicableRule,
      banner: `⚠ 이 조건카드에는 담보유지비율 조항이 없습니다 — 계좌 원장의 ${led}와 맞춰 볼 값이 없어 처분 수량을 산정하지 않습니다.${noBasisNote}`,
      blockReason: "조건카드에 담보유지비율 조항이 없습니다 — 처분 수량을 추정하지 않습니다",
      evidenceNote: `이 조건카드에는 담보유지비율 조항이 없습니다 — 계산의 기준값이 없어 임계가·담보부족액을 산출하지 않았습니다. 계좌 원장의 ${led}로 대신 메우지 않습니다.`,
      detail: `이 조건카드에는 담보유지비율 조항이 없어 산출하지 않았습니다 — 계좌 원장의 ${led}로 대신 메우지 않습니다. 카드에 조항을 채워 넣은 뒤 다시 보세요.`,
    };
  }

  const cards = pctList(agreement.cardRatios);

  if (agreement.why === "AMBIGUOUS") {
    // 카드 안에서 값이 갈렸다. 화면이 그중 하나를 고르면 답이 배열 순서에 의존한다.
    return {
      agreement,
      confirmed: false,
      applicableRule,
      banner: `⚠ 유지비율을 하나로 좁히지 못했습니다 — 이 조건카드에 ${cards}가 함께 있습니다(계좌 원장 ${led}). 화면이 그중 하나를 고르지 않습니다.${noBasisNote}`,
      blockReason: `조건카드의 유지비율이 하나로 좁혀지지 않습니다(${cards}) — 처분 수량을 추정하지 않습니다`,
      evidenceNote: `이 카드에는 유지비율이 ${cards}로 함께 있어 어느 조항이 이 계좌에 걸리는지 화면이 고르지 않습니다 — 그래서 임계가·담보부족액을 산출하지 않았습니다. 계좌 원장의 ${led}로 대신 메우지 않습니다.`,
      detail: `이 조건카드에는 유지비율이 ${cards}로 함께 있어 화면이 그중 하나를 고르지 않습니다 — 산출하지 않았습니다. 계좌 원장의 ${led}로 대신 메우지 않습니다. 어느 조항이 이 계좌에 걸리는지 확인한 뒤 다시 보세요.`,
    };
  }

  // COMPARED && !agreed — 카드에서 하나로 좁혔는데 원장과 값이 다르다.
  // 두 숫자를 나란히 놓는 데까지만 말한다. 어느 쪽이 맞는지는 판정하지 않는다.
  // "옆 값"이라고 쓸 수 있는 것은 근거 패널이 **이 대조가 고른 조항**을 찍기
  // 때문이다(applicableRule). 그 배선이 끊기면 이 문장은 화면에 없는 숫자를
  // 가리키게 되므로, 문구와 배선을 따로 손대지 말 것.
  return {
    agreement,
    confirmed: false,
    applicableRule,
    banner: `⚠ 유지비율이 두 곳에서 다릅니다 — 조건카드 ${cards}, 계좌 원장 ${led}. 어느 쪽이 이 계좌에 맞는지는 화면이 판정하지 않습니다.${basisNote(cards)}`,
    blockReason: `조건카드의 유지비율 ${cards}와 계좌 원장의 유지비율 ${led}가 같지 않습니다 — 처분 수량을 추정하지 않습니다`,
    evidenceNote: `이 화면의 임계가·담보부족액은 조건카드의 유지비율 ${cards}로 산출했습니다 — 계좌 원장은 같은 자리에 ${led}를 적고 있어 같지 않습니다. 어느 쪽이 이 계좌에 맞는 값인지는 화면이 판정하지 않습니다.`,
    detail: `조건카드의 유지비율 ${cards}로 산출한 값입니다. 계좌 원장은 같은 자리에 ${led}를 적고 있습니다 — 두 값이 같지 않아 처분 수량은 산정하지 않습니다. 어느 쪽이 맞는지는 화면이 판정하지 않으니, 계좌의 유지비율과 카드의 조항을 맞춰 본 뒤 다시 보세요.`,
  };
}
